%% build_model.m  —  程序化构建单相 PWM 整流器 Simulink 模型
% =========================================================================
% 功能：用 add_block / add_line 以"纯代码"方式自动搭建整个 Simulink 模型，
%       无需手工拖拽，保证模型可版本管理、跨机器一键复现。
% 工具箱：Simscape Electrical Specialized Power Systems（sps_lib, R2024a）。
%
% 主电路拓扑（单相全桥 PWM 整流器）：
%   Vs(220Vrms/50Hz) ── L_in ── [IGBT H 桥, Arms=2] ── Cdc ∥ (R1 + breaker(R2))
%   交流电网经输入电感接到 H 桥交流侧；H 桥直流侧并联大电容 Cdc 与负载电阻；
%   Breaker 在指定时刻投切第二个电阻，模拟负载突变。
%
% 控制结构（两个 MATLAB Function 块）：
%   Controller（离散 100μs）：开环电网同步 + 电压外环 PI（带 20Hz 低通）
%                              + 电流内环前馈解耦 + PI，输出调制比 ma。
%   SPWM      （离散  2μs ）：ma 与 10kHz 三角载波比较，输出 4 路门极脉冲。
%
% 输出：matlab/model/pwm_rectifier.slx
%
% 子函数：
%   build_controller_code  —— 生成 Controller 块的 MATLAB Function 源码字符串
%   build_spwm_code        —— 生成 SPWM 块的源码字符串
%   set_emlchart_script    —— 把源码与采样率写入对应 MATLAB Function 块
% 注意：上述源码以 sprintf 拼接，字符串内的百分号需写成 %% 才会输出单个 %。
% =========================================================================

function build_model()

%% 路径解析与参数加载
this_file = mfilename('fullpath');
[code_dir,~,~] = fileparts(this_file);
proj_dir  = fileparts(code_dir);
model_dir = fullfile(proj_dir, 'model');
mdl       = 'pwm_rectifier';                        % 模型名
mdl_path  = fullfile(model_dir, [mdl '.slx']);

% 载入 params_calc 计算好的参数结构体 P
S = load(fullfile(model_dir, 'pwm_rectifier_params.mat'), 'P');
P = S.P;
assignin('base', 'P', P);                           % 推到 base 工作区

%% 关闭并删除已存在的同名模型（保证全新构建）
if bdIsLoaded(mdl); close_system(mdl, 0); end
if exist(mdl_path, 'file'); delete(mdl_path); end

%% 加载 SPS 库（提供电源/无源器件/电力电子/测量等模块）
load_system('sps_lib');

%% 新建模型并配置求解器
new_system(mdl);
set_param(mdl, ...
    'Solver',     'ode23tb', ...                    % 刚性系统专用隐式求解器
    'SolverType', 'Variable-step', ...
    'MaxStep',    '1e-5', ...                        % 最大步长 10μs
    'RelTol',     '1e-3', ...
    'AbsTol',     '1e-4', ...
    'StopTime',   num2str(P.Tsim), ...
    'SaveOutput', 'off', ...
    'SaveState',  'off');

%% ===== powergui（SPS 模型必须的电气求解环境模块）=====
add_block('powerlib/powergui', [mdl '/powergui'], 'Position', [20 20 80 60]);
set_param([mdl '/powergui'], 'SimulationMode', 'Continuous');   % 连续求解模式

%% ===== 交流电源 Vs =====
% SPS 的 AC Voltage Source 在 Phase=0 时输出 V(t) = -Vsm·sin(ωt)（注意负号，
% 控制器代码里据此对相位做了翻转）。
add_block('sps_lib/Sources/AC Voltage Source', [mdl '/Vs'], ...
    'Amplitude', num2str(P.Vsm), 'Phase', '0', 'Frequency', num2str(P.f), ...
    'Position', [120 100 160 140]);

%% ===== 输入电感 L_in（RL 串联支路，含寄生电阻 RL）=====
add_block('sps_lib/Passives/Series RLC Branch', [mdl '/L_in'], ...
    'BranchType', 'RL', ...
    'Resistance', num2str(P.RL), ...
    'Inductance', num2str(P.L), ...
    'Position',   [220 90 280 130]);

%% ===== 输入电流测量 Is（串在电感支路上）=====
add_block('sps_lib/Sensors and Measurements/Current Measurement', ...
    [mdl '/Is_meas'], 'Position', [310 90 350 130]);

%% ===== 通用桥 H_Bridge（2 桥臂 = 单相全桥，器件为 IGBT/二极管）=====
add_block('sps_lib/Power Electronics/Universal Bridge', [mdl '/H_Bridge'], ...
    'Arms', '2', ...                                % 2 个桥臂 → H 桥
    'Device', 'IGBT / Diodes', ...                  % IGBT + 反并联二极管
    'SnubberResistance', num2str(P.sel.Snubber_R), ...  % 缓冲电阻
    'SnubberCapacitance', 'inf', ...                % 缓冲电容关闭
    'Ron', '1e-3', ...                              % 导通电阻
    'Position', [400 70 470 190]);

%% ===== 直流母线电容 Cdc（C 支路，预置初始电压 ≈311V 实现软启动）=====
add_block('sps_lib/Passives/Series RLC Branch', [mdl '/Cdc'], ...
    'BranchType', 'C', ...
    'Capacitance', num2str(P.C), ...
    'Setx0', 'on', ...                              % 启用初始电压设置
    'InitialVoltage', num2str(P.Vc_init), ...       % 初值 = 电网峰值，避免启动浪涌
    'Position', [530 90 580 140]);

%% ===== 直流母线电压测量 Vdc（跨接在 Cdc 两端）=====
add_block('sps_lib/Sensors and Measurements/Voltage Measurement', ...
    [mdl '/Vdc_meas'], 'Position', [530 200 580 240]);

%% ===== 负载：两个 2R 电阻并联=R；Breaker 投切其中之一实现负载突变 =====
add_block('sps_lib/Passives/Series RLC Branch', [mdl '/R_load_1'], ...
    'BranchType', 'R', 'Resistance', num2str(P.R_load_2), ...
    'Position', [650 90 700 140]);

% Breaker：在 t_load_off 与 t_load_on 时刻切换，实现 100%→50%→100% 负载
add_block('sps_lib/Power Grid Elements/Breaker', [mdl '/Sw_load'], ...
    'SwitchingTimes', sprintf('[%g %g]', P.t_load_off, P.t_load_on), ...
    'External', 'off', ...
    'InitialState', '1', ...                        % 初始闭合（满载）
    'BreakerResistance', '1e-3', ...
    'SnubberResistance', '1e6', ...
    'SnubberCapacitance', 'inf', ...
    'Position', [580 170 620 210]);

add_block('sps_lib/Passives/Series RLC Branch', [mdl '/R_load_2'], ...
    'BranchType', 'R', 'Resistance', num2str(P.R_load_2), ...
    'Position', [650 170 700 220]);

%% ===== 负载电流测量 Idc（串在 R_load_1 支路上）=====
add_block('sps_lib/Sensors and Measurements/Current Measurement', ...
    [mdl '/Idc_meas'], 'Position', [720 90 760 130]);

%% ===== 电网电压测量 Vs（跨接在交流电源两端）=====
add_block('sps_lib/Sensors and Measurements/Voltage Measurement', ...
    [mdl '/Vs_meas'], 'Position', [120 200 160 240]);

%% ===== Vdc 给定的软启动（Ramp + Saturation 实现分段斜坡）=====
% 策略：t_softstart_begin 之前 Vdc_ref 维持 Vsm（电容经二极管自然预充电），
%       之后线性上升，到 t_softstart 时达到 400V，再被 Saturation 限幅锁定。
ramp_slope = (P.Vdc - P.Vsm) / (P.t_softstart - P.t_softstart_begin);   % 斜坡斜率
add_block('simulink/Sources/Ramp', [mdl '/Vdc_ref'], ...
    'slope', num2str(ramp_slope), ...
    'start', num2str(P.t_softstart_begin), ...      % 斜坡起始时刻
    'InitialOutput', num2str(P.Vsm), ...            % 起始值 = 电网峰值
    'Position', [120 320 160 360]);
add_block('simulink/Discontinuities/Saturation', [mdl '/Vdc_ref_sat'], ...
    'UpperLimit', num2str(P.Vdc), 'LowerLimit', num2str(P.Vsm), ...
    'Position', [180 320 220 360]);

%% ===== 时钟 Clk（为控制器与 SPWM 提供时间 t）=====
add_block('simulink/Sources/Clock', [mdl '/Clk'], 'Position', [120 400 160 430]);

%% ===== 控制器 Controller（MATLAB Function 块，离散 @ Ts_ctrl=100μs）=====
% 仅输出调制比 ma（SPWM 放在独立快速块中，二者解耦）。
add_block('simulink/User-Defined Functions/MATLAB Function', ...
    [mdl '/Controller'], 'Position', [300 280 480 380]);
ctrl_code = build_controller_code(P);               % 生成控制器源码
set_emlchart_script(mdl, 'Controller', ctrl_code, P.Ts_ctrl);

%% ===== SPWM 调制器（MATLAB Function 块，快速 @ Ts_power=2μs）=====
% 输入 ma 与 t，输出 4 路门极脉冲 g1..g4；三角载波在每个 Ts_power 采样一次。
add_block('simulink/User-Defined Functions/MATLAB Function', ...
    [mdl '/SPWM'], 'Position', [560 280 720 380]);
spwm_code = build_spwm_code(P);                     % 生成 SPWM 源码
set_emlchart_script(mdl, 'SPWM', spwm_code, P.Ts_power);

%% ===== Mux：把 4 路脉冲合成一个向量送入 H 桥的 g 端口 =====
add_block('simulink/Signal Routing/Mux', [mdl '/PulseMux'], ...
    'Inputs', '4', 'Position', [760 320 770 410]);

%% ===== To Workspace：记录 5 路信号到工作区 =====
sigs = {'Vs','Is','Vdc','Idc','Vdc_ref'};
for k = 1:numel(sigs)
    add_block('simulink/Sinks/To Workspace', [mdl '/log_' sigs{k}], ...
        'VariableName', sigs{k}, ...
        'SaveFormat', 'Structure With Time', ...    % 含时间的结构体格式
        'SampleTime', '-1', ...                     % 继承输入信号采样率
        'Position', [850 70+50*(k-1) 920 100+50*(k-1)]);
end

%% ===== 接线：电气连接（功率回路）=====
% Vs+ → L_in → Is_meas → 桥交流端 AC1（桥的 LConn1）
add_line(mdl, 'Vs/LConn1',       'L_in/LConn1',     'autorouting','on');
add_line(mdl, 'L_in/RConn1',     'Is_meas/LConn1',  'autorouting','on');
add_line(mdl, 'Is_meas/RConn1',  'H_Bridge/LConn1', 'autorouting','on');
% Vs- → 桥交流端 AC2（桥的 LConn2）
add_line(mdl, 'Vs/RConn1',       'H_Bridge/LConn2', 'autorouting','on');

% 桥直流正端 DC+ → Cdc 上端（直流母线+）→ Vdc_meas+；再经 Idc_meas 到负载上端
add_line(mdl, 'H_Bridge/RConn1', 'Cdc/LConn1',      'autorouting','on');
add_line(mdl, 'Cdc/LConn1',      'Vdc_meas/LConn1', 'autorouting','on');
add_line(mdl, 'Cdc/LConn1',      'Idc_meas/LConn1', 'autorouting','on');
add_line(mdl, 'Idc_meas/RConn1', 'R_load_1/LConn1', 'autorouting','on');
add_line(mdl, 'Idc_meas/RConn1', 'Sw_load/LConn1',  'autorouting','on');
add_line(mdl, 'Sw_load/RConn1',  'R_load_2/LConn1', 'autorouting','on');

% 所有负载下端 + Cdc 下端 + Vdc_meas- → 桥直流负端 DC-
add_line(mdl, 'R_load_1/RConn1', 'H_Bridge/RConn2', 'autorouting','on');
add_line(mdl, 'R_load_2/RConn1', 'H_Bridge/RConn2', 'autorouting','on');
add_line(mdl, 'Cdc/RConn1',      'H_Bridge/RConn2', 'autorouting','on');
add_line(mdl, 'Vdc_meas/LConn2', 'H_Bridge/RConn2', 'autorouting','on');

% 电网电压测量并联在交流电源两端
add_line(mdl, 'Vs/LConn1', 'Vs_meas/LConn1', 'autorouting','on');
add_line(mdl, 'Vs/RConn1', 'Vs_meas/LConn2', 'autorouting','on');

%% ===== 接线：信号连接（控制回路）=====
% 测量量 → 控制器输入：1=Vs, 2=Is, 3=Vdc, 4=Vdc_ref, 5=t
add_line(mdl, 'Vs_meas/1',     'Controller/1', 'autorouting','on');
add_line(mdl, 'Is_meas/1',     'Controller/2', 'autorouting','on');
add_line(mdl, 'Vdc_meas/1',    'Controller/3', 'autorouting','on');
add_line(mdl, 'Vdc_ref/1',     'Vdc_ref_sat/1','autorouting','on');
add_line(mdl, 'Vdc_ref_sat/1', 'Controller/4', 'autorouting','on');
add_line(mdl, 'Clk/1',         'Controller/5', 'autorouting','on');

% 控制器输出 ma → SPWM 输入1；时钟 t → SPWM 输入2
add_line(mdl, 'Controller/1', 'SPWM/1', 'autorouting','on');  % ma
add_line(mdl, 'Clk/1',        'SPWM/2', 'autorouting','on');  % t
% SPWM 输出 g1..g4 → Mux → 桥的 g 端口
add_line(mdl, 'SPWM/1', 'PulseMux/1', 'autorouting','on');
add_line(mdl, 'SPWM/2', 'PulseMux/2', 'autorouting','on');
add_line(mdl, 'SPWM/3', 'PulseMux/3', 'autorouting','on');
add_line(mdl, 'SPWM/4', 'PulseMux/4', 'autorouting','on');
add_line(mdl, 'PulseMux/1', 'H_Bridge/1', 'autorouting','on');

% 5 路信号接到 To Workspace 记录块
add_line(mdl, 'Vs_meas/1',     'log_Vs/1',     'autorouting','on');
add_line(mdl, 'Is_meas/1',     'log_Is/1',     'autorouting','on');
add_line(mdl, 'Vdc_meas/1',    'log_Vdc/1',    'autorouting','on');
add_line(mdl, 'Idc_meas/1',    'log_Idc/1',    'autorouting','on');
add_line(mdl, 'Vdc_ref_sat/1', 'log_Vdc_ref/1','autorouting','on');

%% ===== 保存模型 =====
save_system(mdl, mdl_path);
close_system(mdl, 0);
fprintf('[build_model] Model saved to: %s\n', mdl_path);

end


%% =========================================================================
function code = build_controller_code(P)
% 生成 Controller 块的 MATLAB Function 源码字符串。
% 控制律：开环电网同步 + 电压外环 PI（含 20Hz 低通）+ 电流内环前馈解耦 + PI，
%         仅输出调制比 ma（SPWM 在独立快速块中完成）。
% 注意：下面字符串中所有 %% 在 sprintf 后会变成单个 %（即生成代码里的注释）；
%       结尾的 %g 是 sprintf 占位符，用 P 的字段按顺序填入。
code = sprintf([ ...
'function ma = fcn(Vs,Is,Vdc,Vdc_ref,t)\n' ...
'%%#codegen\n' ...
'persistent int_v int_i vdc_f\n' ...
'if isempty(int_v)\n' ...
'    int_v = 0;\n' ...
'    int_i = 0;\n' ...
'    vdc_f = 0;\n' ...
'end\n' ...
'Ts     = %g;\n' ...
'f      = %g;\n' ...
'fsw    = %g;\n' ...
'omega  = 2*pi*f;\n' ...
'L      = %g;\n' ...
'RL     = %g;\n' ...
'Kp_v   = %g; Ki_v = %g; Im_lim = %g;\n' ...
'Kp_i   = %g; Ki_i = %g; Vm_lim = %g;\n' ...
'fc_v   = 20;\n' ...
'%% --- 电网相位（开环同步，f=50Hz 已知）---\n' ...
'%% SPS 交流源 Phase=0 时输出 V(t)=-Vsm*sin(wt)，故此处对正余弦取负号校正。\n' ...
'theta = omega*t;\n' ...
'theta = theta - 2*pi*floor(theta/(2*pi));\n' ...
'sin_t = -sin(theta);\n' ...
'cos_t = -cos(theta);\n' ...
'%% --- Vdc 低通滤波（抑制误差中的 100Hz 纹波）---\n' ...
'alpha = 2*pi*fc_v*Ts/(1 + 2*pi*fc_v*Ts);\n' ...
'vdc_f = vdc_f + alpha*(Vdc - vdc_f);\n' ...
'%% --- 电压外环 PI ---\n' ...
'ev    = Vdc_ref - vdc_f;\n' ...
'int_v = int_v + Ts*ev;\n' ...
'Im_ref = Kp_v*ev + Ki_v*int_v;\n' ...
'if Im_ref >  Im_lim\n' ...
'    Im_ref =  Im_lim;\n' ...
'    int_v = (Im_lim - Kp_v*ev)/Ki_v;\n' ...
'elseif Im_ref < 0\n' ...
'    Im_ref = 0;\n' ...
'    int_v = (-Kp_v*ev)/Ki_v;\n' ...
'end\n' ...
'%% --- 电流给定（与电网同相的正弦）---\n' ...
'i_ref     = Im_ref * sin_t;\n' ...
'di_ref_dt = Im_ref * omega * cos_t;\n' ...
'%% --- 电流内环：前馈解耦 + 小幅 PI 校正 ---\n' ...
'%% 物理依据：L*dIs/dt + RL*Is = Vs - V_ab。要跟踪 i_ref，令：\n' ...
'%%   V_ab_ff = Vs - L*di_ref/dt - RL*i_ref （开环解析跟踪解）\n' ...
'V_ab_ff = Vs - L*di_ref_dt - RL*i_ref;\n' ...
'%% PI 作用于跟踪误差 ei = Is - i_ref。ei>0（电流偏大）→ 抬高 V_ab。\n' ...
'ei    = Is - i_ref;\n' ...
'int_i = int_i + Ts*ei;\n' ...
'vm    = V_ab_ff + Kp_i*ei + Ki_i*int_i;\n' ...
'if vm >  Vm_lim\n' ...
'    vm =  Vm_lim;\n' ...
'    int_i = (Vm_lim - V_ab_ff - Kp_i*ei)/Ki_i;\n' ...
'elseif vm < -Vm_lim\n' ...
'    vm = -Vm_lim;\n' ...
'    int_i = (-Vm_lim - V_ab_ff - Kp_i*ei)/Ki_i;\n' ...
'end\n' ...
'%% --- 把调制电压 vm 换算成调制比 ma ---\n' ...
'%% 用滤波后的 Vdc，避免 100Hz 纹波注入 ma。\n' ...
'Vdc_safe = vdc_f;\n' ...
'if Vdc_safe < 50\n' ...
'    Vdc_safe = 50;\n' ...
'end\n' ...
'%% 全桥双极性 SPWM：V_ab 平均值 = ma*Vdc，故 ma = vm/Vdc。\n' ...
'ma = vm / Vdc_safe;\n' ...
'if ma >  1\n' ...
'    ma =  1;\n' ...
'end\n' ...
'if ma < -1\n' ...
'    ma = -1;\n' ...
'end\n' ...
'end\n'], ...
P.Ts_ctrl, P.f, P.fsw, P.L, P.RL, ...
P.Kp_v, P.Ki_v, P.Im_lim, ...
P.Kp_i, P.Ki_i, P.I_limit);
end


%% =========================================================================
function code = build_spwm_code(P)
% 生成 SPWM 块的 MATLAB Function 源码字符串。
% 双极性 SPWM：以 fsw 的三角载波与调制比 ma 比较，输出 H 桥 4 路互补门极。
% 运行在快速采样率（Ts_power）下，使三角载波有足够的离散化分辨率。
code = sprintf([ ...
'function [g1,g2,g3,g4] = fcn(ma_in,t)\n' ...
'%%#codegen\n' ...
'fsw = %g;\n' ...
'Tcar = 1/fsw;\n' ...
'phase = t/Tcar - floor(t/Tcar);\n' ...
'if phase < 0.5\n' ...
'    tri = 4*phase - 1;\n' ...
'else\n' ...
'    tri = 3 - 4*phase;\n' ...
'end\n' ...
'ma = ma_in;\n' ...
'if ma >  1\n' ...
'    ma =  1;\n' ...
'end\n' ...
'if ma < -1\n' ...
'    ma = -1;\n' ...
'end\n' ...
'sA = double(ma >  tri);\n' ...
'sB = double(-ma >  tri);\n' ...
'g1 = sA;\n' ...
'g2 = 1 - sA;\n' ...
'g3 = sB;\n' ...
'g4 = 1 - sB;\n' ...
'end\n'], P.fsw);
end


%% =========================================================================
function set_emlchart_script(mdl, blkname, code, sample_time)
% 把生成的源码字符串写入指定 MATLAB Function 块，并设置其离散采样率。
% 实现：通过 Stateflow 根对象找到该块对应的 EMChart，写入 Script 属性，
%       再把更新方式设为离散并指定 SampleTime。
load_system(mdl);
rt = sfroot;
m  = rt.find('-isa','Stateflow.Machine','Name', mdl);
if isempty(m)
    error('Stateflow machine for model "%s" not found.', mdl);
end
charts = m.find('-isa','Stateflow.EMChart');
chart = [];
for ii = 1:numel(charts)
    if strcmp(charts(ii).Path, [mdl '/' blkname])
        chart = charts(ii);
        break;
    end
end
if isempty(chart)
    error('MATLAB Function chart "%s" not found.', blkname);
end
chart.Script = code;
if nargin >= 4 && ~isempty(sample_time)
    try
        chart.ChartUpdate = 'DISCRETE';
        chart.SampleTime  = num2str(sample_time);
    catch
        % 旧版本 API 不支持时忽略
    end
end
end
